-- cars.sql — the database of MvvmSupabaseSimpleApp
--
-- One table in public, read and updated directly through the Data API
-- (no views, no RPC — the "plain Supabase" way):
--
--   public.cars (id, brand, model, year, color, price, updated_at)
--
-- Who may do what — GRANTs decide the commands, RLS decides the rows:
--   anon           nothing (no grants, and no policy would let a row through)
--   authenticated  everything: SELECT, INSERT, UPDATE, DELETE on every row
--                  (the app itself only reads and changes 'model')
--
-- How to run — idempotent: drops and re-creates the table, your edits included.
--   * Dashboard → SQL Editor → paste this file → Run
--   * or: psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -1 -f cars.sql
--   * or: uv run sbcli db sql -f …/cars.sql   (in python_supabase)
--   A user to log in with: Dashboard → Authentication → Add user (or sbcli).
--
-- Next to python_supabase in the same project (MobAppDemo) — good to know:
--   * The table lives in public, the data of mobappdata stays untouched; the
--     names don't clash (public.products etc. are views, there is no 'cars').
--   * `sbcli db reset` drops schema public (cascade) → cars is gone, too.
--     Simply run this script again afterwards.
--   * `sbcli db check` reports 1 failed check: "no tables in public (API only)".
--     That is the point of the comparison: here the table IS the API.
--   * 99_api_handover.sql (re-run by `sbcli db apply`) grants SELECT on all
--     tables in public to authenticated — already granted here, no harm.
-- =============================================================================

-- --- 0. reset ----------------------------------------------------------------
drop table if exists public.cars cascade;
drop function if exists public.cars_set_updated_at();

-- --- 1. table ----------------------------------------------------------------
create table public.cars (
  id          integer generated by default as identity primary key,
  brand       varchar(50)    not null check (btrim(brand) <> ''),
  model       varchar(100)   not null check (btrim(model) <> ''),
  year        integer        not null check (year between 1886 and 2100),
  color       varchar(30)    not null default 'black',
  price       numeric(12, 2) not null default 0.00 check (price >= 0),
  updated_at  timestamptz    not null default now()
);
comment on table public.cars is 'MvvmSupabaseSimpleApp: cars, used directly through the Data API (RLS: signed-in users only).';

-- --- 2. trigger: updated_at is set by the database, not by the app -------------
create function public.cars_set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger cars_updated_at
  before update on public.cars
  for each row execute function public.cars_set_updated_at();

-- a trigger function is nothing to call via /rpc
revoke all on function public.cars_set_updated_at() from public, anon, authenticated;

