-- --- 4. privileges (GRANT): which commands ------------------------------------
-- Explicit, because the defaults in public differ between projects (and after
-- `sbcli db reset`, 00_reset.sql sets its own).
revoke all on public.cars from public, anon;
grant select, insert, update, delete on public.cars to authenticated;

-- --- 5. row level security (RLS): which rows -----------------------------------
-- With RLS on, a command sees no row unless a policy lets it through.
alter table public.cars enable row level security;

create policy "cars: signed-in users may do everything"
  on public.cars for all to authenticated
  using (true)            -- which existing rows may be read/changed/deleted
  with check (true);      -- what inserted/changed rows may look like

